"""連用形串接的子句:「〜フィールドに戻り、その攻撃力は〜になる」「〜を手札に加え、このカードをデッキに戻す」
「装備モンスターは相手の効果の対象にならず、戦闘では破壊されない」以「、」切成多個段,連接記「同時」
(spec 段樹:序列帶連接)。

形狀判斷先切(spec「多子句串接怎麼切?」):「、」前面那截以已知的連用形語尾
(`CONTINUATIVE_TAILS`)收尾就切,兩截各自解析;左半解不出時
只有它標解析不出。不切的:接續詞(ただし、しかし、もし)與以「限り」「により」「につき」「を除き」
「とき」、形容詞/否定的終止形(ない、高い…)收尾的(`NOT_CONTINUATIVE`);以 の/は/を/に 收尾的
(「自分フィールドの、「A」または「B」が」「攻撃力は、」)不在語尾閉集裡,本來就不切。
「」『』（）內的「、」不算。
票 06 的「し、」同時連接(含發動句的代價子句「〜を墓地へ送り、〜を対象として発動できる」)
也走這裡;句子以上的結構(● 分歧、內嵌效果)在 `segment_tree`。
"""

# 連用形語尾閉集:否定連用形「ず」(ならず、されず、できず、受けず、送らず)、五段/サ變的
# し、り、い、き(破壊し、送り、払い、取り除き;なり、になり 屬「り」)、一段的 え(加え、与え),
# 與不以 え 收尾的一段動詞/サ變名詞字幹(捨て、見せ、上げ…、リリース)。
CONTINUATIVE_TAILS = ("ず", "し", "り", "い", "き", "え",
                      "捨て", "見せ", "上げ", "下げ", "捧げ", "受け", "リリース")
# 語尾落在閉集裡、但不是動詞連用形的收尾:接續詞、助詞性的「限り」「により」「につき」「を除き」
# 「とき」,形容詞與否定的終止/連體形(「ランクが１つ高い、」是名詞修飾)。
NOT_CONTINUATIVE = ("ただし", "しかし", "もし", "限り", "により", "につき", "を除き", "とき",
                    "ない", "高い", "低い", "強い")
JOIN = "同時"
_OPEN = "「『（"
_CLOSE = "」』）"


def is_continuative(left):
    """「、」左半是否以連用形語尾收尾(看形狀,不解析)。"""
    return left.endswith(CONTINUATIVE_TAILS) and not left.endswith(NOT_CONTINUATIVE)


def split_continuative(text):
    """子句原文 → [(相對起點, 子句字面)];「、」左半以連用形語尾收尾才在那裡切。"""
    pieces, depth, last = [], 0, 0
    for i, ch in enumerate(text):
        if ch in _OPEN:
            depth += 1
        elif ch in _CLOSE:
            depth -= 1
        elif ch == "、" and depth == 0 and is_continuative(text[last:i]):
            pieces.append((last, text[last:i]))
            last = i + 1
    pieces.append((last, text[last:]))
    return pieces
